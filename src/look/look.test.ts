import { describe, expect, it } from 'vitest';

import { identityLut, sampleLut } from '../lut/lut';
import type { Lut } from '../lut/lut';
import { INVERT_CUBE } from '../test-support/look-cubes';

import {
  applyLook,
  blendColor,
  blendLuts,
  isCubeFile,
  isLogConversion,
  lookName,
  lookSlug,
  lookedLut,
  parseLookCube,
  sampleLook,
} from './look';
import type { LookLut, LookProblem } from './look';

// The value lines of the inverting look, for files with other headers.
const INVERT_LINES = INVERT_CUBE.split('\n').slice(1);

function cube(...header: string[]): string {
  return [...header, ...INVERT_LINES].join('\n');
}

// Checks that the parser rejects the text with this problem.
function rejects(text: string, key: LookProblem['key'], params: LookProblem['params'] = {}) {
  expect(() => parseLookCube('a.cube', text)).toThrow(
    expect.objectContaining({ problem: { key, params } }),
  );
}

function invertLook(): LookLut {
  return parseLookCube('Invert.cube', cube('LUT_3D_SIZE 2'));
}

function expectClose(actual: readonly number[], expected: readonly number[]): void {
  for (const [index, value] of expected.entries()) {
    expect(actual[index]).toBeCloseTo(value, 5);
  }
}

describe('parseLookCube', () => {
  it('reads a 3D LUT and names it after the file', () => {
    const look = parseLookCube(
      '05 Teal.cube',
      cube('# made up', 'TITLE "Generated by Resolve"', 'LUT_3D_SIZE 2', ''),
    );
    expect(look.name).toBe('05 Teal');
    expect(look.lut.size).toBe(2);
    expect([...look.lut.data.slice(0, 6)]).toEqual([1, 1, 1, 0, 1, 1]);
    expect(look.min).toEqual([0, 0, 0]);
    expect(look.max).toEqual([1, 1, 1]);
  });

  it('accepts Windows line breaks, lower case keywords and unknown keywords', () => {
    const text = ['lut_3d_size 2', 'LUT_IN_VIDEO_RANGE', ...INVERT_LINES].join('\r\n');
    expect(parseLookCube('a.cube', text).lut.size).toBe(2);
  });

  it('reads the input range from DOMAIN_MIN/MAX or LUT_3D_INPUT_RANGE', () => {
    const domain = parseLookCube(
      'a.cube',
      cube('DOMAIN_MIN 0 0 -0.5', 'DOMAIN_MAX 1 2 1', 'LUT_3D_SIZE 2'),
    );
    expect(domain.min).toEqual([0, 0, -0.5]);
    expect(domain.max).toEqual([1, 2, 1]);
    const range = parseLookCube('a.cube', cube('LUT_3D_INPUT_RANGE 0.1 0.9', 'LUT_3D_SIZE 2'));
    expect(range.min).toEqual([0.1, 0.1, 0.1]);
    expect(range.max).toEqual([0.9, 0.9, 0.9]);
  });

  it('rejects 1D LUTs', () => {
    rejects('LUT_1D_SIZE 1024\n0 0 0', 'oneDimensional');
  });

  it('rejects files without a 3D size, also when the values come first', () => {
    rejects('TITLE "x"', 'noSize');
    rejects(cube(), 'noSize');
  });

  it('rejects sizes outside 2 to 129', () => {
    const range = { min: 2, max: 129 };
    rejects('LUT_3D_SIZE 1', 'size', { size: '1', ...range });
    rejects('LUT_3D_SIZE 130', 'size', { size: '130', ...range });
    rejects('LUT_3D_SIZE 2.5', 'size', { size: '2.5', ...range });
    rejects('LUT_3D_SIZE', 'size', { size: 'undefined', ...range });
  });

  it('names the line with broken numbers', () => {
    rejects(['LUT_3D_SIZE 2', '0 0 0', '1 x 0'].join('\n'), 'numbers', { line: 3 });
    rejects('DOMAIN_MIN 0 0', 'numbers', { line: 1 });
    rejects('LUT_3D_INPUT_RANGE 0', 'numbers', { line: 1 });
  });

  it('rejects too few or too many value lines', () => {
    const few = ['LUT_3D_SIZE 2', ...INVERT_LINES.slice(1)].join('\n');
    rejects(few, 'count', { expected: 8, actual: 7 });
    const many = [...cube('LUT_3D_SIZE 2').split('\n'), '0 0 0'].join('\n');
    rejects(many, 'count', { expected: 8, actual: 9 });
  });

  it('rejects an empty input range', () => {
    rejects(cube('DOMAIN_MIN 0 0.5 0', 'DOMAIN_MAX 1 0.5 1', 'LUT_3D_SIZE 2'), 'domain');
  });
});

describe('file names', () => {
  it('recognizes .cube files and takes the name without the extension', () => {
    expect(isCubeFile('Look.CUBE')).toBe(true);
    expect(isCubeFile('look.3dl')).toBe(false);
    expect(lookName('01 MH Cold Vibes.cube')).toBe('01 MH Cold Vibes');
    expect(lookName('.cube')).toBe('.cube');
  });

  it('recognizes conversions from camera log curves by their name', () => {
    for (const name of [
      'SLOG 3 S CINETONE_REC709',
      'S-Log3 to 709',
      'ARRI LogC',
      'V-Log',
      'Log3G10',
    ]) {
      expect(isLogConversion(name)).toBe(true);
    }
    for (const name of ['02 MH Moody Warm', 'Blog look', 'Teal And Orange']) {
      expect(isLogConversion(name)).toBe(false);
    }
  });

  it('makes a short file name part of the look name', () => {
    expect(lookSlug('05 MH Teal And Orange FILMIC')).toBe('05-mh-teal-and-orange-filmic');
    expect(lookSlug('Kühl & grün!')).toBe('kuhl-grun');
    expect(lookSlug('***')).toBe('');
  });
});

describe('applying a look', () => {
  it('samples the look, scaled to its input range', () => {
    expectClose(sampleLook(invertLook(), [0.2, 0.5, 1]), [0.8, 0.5, 0]);
    const wide = parseLookCube(
      'a.cube',
      cube('DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 2 2 2', 'LUT_3D_SIZE 2'),
    );
    // 0.5 lies at a quarter of the range 0..2.
    expectClose(sampleLook(wide, [0.5, 0.5, 0.5]), [0.75, 0.75, 0.75]);
  });

  it('passes every grid point of the correction through the look', () => {
    const base = identityLut(3);
    const looked = applyLook(base, invertLook());
    expect(looked.size).toBe(3);
    expectClose(sampleLut(looked, [0.25, 0.5, 1]), [0.75, 0.5, 0]);
  });

  it('mixes correction and look by the strength', () => {
    const base: Lut = { size: 2, data: new Float32Array(24).fill(0.2) };
    const looked: Lut = { size: 2, data: new Float32Array(24).fill(0.6) };
    expectClose([...blendLuts(base, looked, 0).data.slice(0, 3)], [0.2, 0.2, 0.2]);
    expectClose([...blendLuts(base, looked, 0.5).data.slice(0, 3)], [0.4, 0.4, 0.4]);
    expectClose([...blendLuts(base, looked, 1).data.slice(0, 3)], [0.6, 0.6, 0.6]);
    expectClose(blendColor([0, 0.5, 1], [1, 0.5, 0], 0.25), [0.25, 0.5, 0.75]);
  });

  it('leaves the correction alone without a look', () => {
    const base = identityLut(2);
    expect(lookedLut(base, null, 1)).toBe(base);
    expectClose([...lookedLut(base, invertLook(), 1).data.slice(0, 3)], [1, 1, 1]);
  });
});
