import { APP_NAME } from '../ui/app-info';
import { APP_VERSION } from '../ui/app-version';

import type { Lut } from './lut';

// Allowed export sizes; 33 is a good default, 17 and 65 are common on some devices.
export const CUBE_SIZES = [17, 33, 65] as const;

const DECIMALS = 6;

function format(value: number): string {
  return value.toFixed(DECIMALS);
}

// The first lines of the file: what made it, further notes as comments (such as the look LUT),
// title and size.
function cubeHeader(size: number, title: string, notes: readonly string[] = []): string[] {
  return [
    `# Generated by ${APP_NAME} ${APP_VERSION}`,
    ...notes.map((note) => `# ${note}`),
    // Quotation marks in the title would make the line invalid.
    `TITLE "${title.replaceAll('"', "'")}"`,
    `LUT_3D_SIZE ${String(size)}`,
  ];
}

// Writes the LUT in the Adobe/Resolve .cube format (3D, value range 0..1, R fastest).
// Decimal point and line break are independent of language and system settings.
export function formatCube(lut: Lut, title: string, notes: readonly string[] = []): string {
  const lines = [
    ...cubeHeader(lut.size, title, notes),
    `DOMAIN_MIN ${format(0)} ${format(0)} ${format(0)}`,
    `DOMAIN_MAX ${format(1)} ${format(1)} ${format(1)}`,
  ];
  for (let offset = 0; offset < lut.data.length; offset += 3) {
    lines.push(
      `${format(Number(lut.data[offset]))} ${format(Number(lut.data[offset + 1]))} ${format(Number(lut.data[offset + 2]))}`,
    );
  }
  return `${lines.join('\n')}\n`;
}
